import java.util.Scanner;

public class IT26101701Lab6Q2A {
	
    public static void main(String[] args) {
		
		//Declaring and Initializing the counter variable
		int counter = 1;
		
		//Using a while loop to print number from 1 to 10
		while (counter <= 10) {
			
			//Printing the current number followed by a space
			System.out.print(counter + " ");
			counter++;		//Incrementing the counter
			
		}
		
		// Printing a newline character to move to the next line after printing all numbers
		System.out.println();
        
    }
}
